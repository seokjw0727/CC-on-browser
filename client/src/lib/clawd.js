/**
 * 세션 상태·WS 연결 상태 → 무드.
 *   busy  = thinking|tool (턴 진행 중)
 *   alert = awaiting-permission (권한 응답 대기)
 *   doze  = 세션 없음('none')|exited|연결 끊김
 *   idle  = 그 외 (idle 등)
 */
export function clawdMood(status, conn) {
  if (conn !== 'open') return 'doze';
  switch (status) {
    case 'thinking':
    case 'tool':
      return 'busy';
    case 'awaiting-permission':
      return 'alert';
    case 'exited':
    case 'none':
      return 'doze';
    default:
      return 'idle';
  }
}
